#pragma once

//------------------------------------------------------------------------------
// Запрос высокой частоты обновления экрана на Android.
//
// Android выбирает режим дисплея для приложения сам, и на телефоне с
// 90/120-герцевым экраном окно нередко остаётся в 60 Гц: система экономит
// батарею, пока приложение не попросит больше. Qt Quick частоту не выбирает —
// рисует по vsync текущего режима, поэтому просьба идёт напрямую в окно
// Android: окну назначается самый частотный из поддержанных режимов дисплея
// (`WindowManager.LayoutParams.preferredDisplayModeId`). Абстрактные
// «120 Гц» не годятся: частоты, которой у панели нет, система вправе
// не давать.
//
// Просьба отправляется при каждом запуске на Android (см. main.cpp):
// гладкий скролл и анимации — то, ради чего интерфейс существует, а перегрев
// лечится системным режимом экономии батареи. На других ОС вызов no-op.
//------------------------------------------------------------------------------
class AsAndroid_Frame_Rate
{
public:
	// Отправляет просьбу о максимальной частоте. Возврат true — запрос отправлен;
	// false — частота не запрошена (не Android либо нет активности).
	static bool Request_Highest();
};
//----------------------------------------------------------------------------
