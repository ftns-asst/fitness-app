#pragma once

#include "Domain/Progress_Stats.h"

#include <QDate>
#include <QString>
#include <QVector>

//-------------------------------------------------------------------------------------------------------------
// Общие вычисления над фактами тренировок для калькуляторов статистики.
// Вынесены отдельно, потому что используются и программой, и «всё время»
// (срез W7, рефакторинг): иначе каждая из двух частей считала бы «первое и
// последнее значение» и e1RM по-своему, и формулы разъехались бы.
//
// Даты сравниваются как строки ISO (YYYY-MM-DD): лексикографический порядок
// совпадает с хронологическим, поэтому сортировать факты перед расчётом не
// требуется.
//-------------------------------------------------------------------------------------------------------------

//-------------------------------------------------------------------------------------------------------------
// Крайние величины по дате: самое раннее и самое позднее значение набора.
// Заменяет шесть пар «дата + значение + флаг», повторявшихся в расчёте.
//-------------------------------------------------------------------------------------------------------------
struct SExtremes_Value
{
	double First_Value = 0;
	QString First_Date;
	bool Has_First = false;
	double Last_Value = 0;
	QString Last_Date;
	bool Has_Last = false;

	void Add(const QString &in_date, double in_value);
	bool Has_Both() const;
	double Delta() const;
};

//-------------------------------------------------------------------------------------------------------------
// Номер недели программы от даты старта (0 — дата раньше старта или невалидна).
//-------------------------------------------------------------------------------------------------------------
int Week_Index(const QDate &in_start, const QDate &in_date);
//-------------------------------------------------------------------------------------------------------------
// Понедельник ISO-недели, к которой относится дата (§5.5).
//-------------------------------------------------------------------------------------------------------------
QDate Week_Start(const QDate &in_date);
//-------------------------------------------------------------------------------------------------------------
// Дата внутри окна программы [start, end] включительно.
//-------------------------------------------------------------------------------------------------------------
bool In_Window(const QDate &in_date, const QDate &in_start, const QDate &in_end);
//-------------------------------------------------------------------------------------------------------------
// Дата тренировки: поле даты, иначе дата из отметки времени начала.
//-------------------------------------------------------------------------------------------------------------
QString Session_Date(const SWorkout_Session &in_session);
//-------------------------------------------------------------------------------------------------------------
// Оценка одного повторного максимума по формуле Эпли (§5.2).
//-------------------------------------------------------------------------------------------------------------
double E1rm(const SSet_Log &in_set);
//-------------------------------------------------------------------------------------------------------------
// Подход учитывается в объёме: рабочий, выполненный, с упражнением.
//-------------------------------------------------------------------------------------------------------------
bool Set_Counts_In_Volume(const SSet_Log &in_set);
//-------------------------------------------------------------------------------------------------------------
// Тоннаж подхода: вес × повторения; 0 для подхода, который не засчитывается.
//-------------------------------------------------------------------------------------------------------------
double Set_Tonnage(const SSet_Log &in_set);
//-------------------------------------------------------------------------------------------------------------
// Средний RPE тренировки. false — данных нет: ни Avg_Rpe у сессии, ни RPE
// подходов. Заменяет магический возврат −1 в невозвращаемом типе double.
//-------------------------------------------------------------------------------------------------------------
bool Session_Average_Rpe(const SWorkout_Session &in_session, const QVector<SSet_Log> &in_sets, double &out_average);
//-------------------------------------------------------------------------------------------------------------