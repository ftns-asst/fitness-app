#pragma once

#include <QLoggingCategory>
#include <QString>

//-------------------------------------------------------------------------------------------------------------
// Хранилище ошибки объекта (срез W7, рефакторинг ошибок).
//
// Заменяет копипаст `Last_Error_Text` + `Get_Last_Error()` + `Set_Last_Error()`,
// который повторялся в доменных сервисах, репозиториях и корневом контексте.
// Наследование здесь невозможно: `QObject`-наследники уже имеют базовый тип, а
// CODE_STYLE §4.4 разрешает только один, поэтому состояние входит
// композицией — одинаково во всех классах.
//
// Семантика: «последняя ошибка = результат последнего вызова». Ошибка пишется
// только через Set_Last_Error() (он же логирует в переданную категорию) и
// сбрасывается вызывающим в начале публичного метода через Clear_Last_Error().
//
// Владение: значение копируется в QString владельца, владение не передаётся.
//-------------------------------------------------------------------------------------------------------------
class AError_State
{
public:
	// Без категории ошибка только хранится; логирование — по переданной.
	explicit AError_State(const QLoggingCategory *in_log_category = 0);

	QString Get_Last_Error() const;
	bool Has_Error() const;

	// Всегда возвращает false: вызывающий использует `return Set_Last_Error(...)`.
	bool Set_Last_Error(const QString &in_error);

	// Сброс в начале публичного метода — «ошибка относится к текущему вызову».
	void Clear_Last_Error();

private:
	const QLoggingCategory *Log_Category;
	QString Error_Text;
};
//-------------------------------------------------------------------------------------------------------------